# описание изменений:
# Добавила переход на сайт Playwright, чтобы тесту было что проверять 
# Изменила текст для проверки на логотип (класс navbar__brand), чтобы тест проверял реальный элемент
# Увеличила тайм-аут с 10 до 15 секунд, чтобы дать странице больше времени на загрузку в случае медленного интернета

from playwright.sync_api import Page, expect

def test_foobar(page: Page) -> None:
    # Переходим на сайт
    page.goto("https://playwright.dev/")
    
    # Проверяем видимость логотипа с увеличенным тайм-аутом (15 секунд)
    expect(page.locator(".navbar__brand")).to_be_visible(timeout=15_000)